// Depth-limited minimax with the open-lines e(s) (slides p. 382–389): drag the depth limit and watch the chosen move change.
// Terminal states keep their utility ±1 (terminal test first); the true outcome of each move comes from the full minimax.
import { cell, empties, LINES, minimax, over, put, toMove, winner, type Board } from './adv-ttt-tree';
import { bar, card, md, num, s, slider, style, type FigOptions } from './shell';

type Scale = 'raw' | 'norm';
const PRESETS: { name: string; board: Board; scale: Scale; h: number }[] = [
  { name: 'empty board (p. 386)', board: '.........', scale: 'raw', h: 2 },
  { name: 'a win beyond the horizon', board: '..O.....X', scale: 'norm', h: 1 },
  { name: 'a loss beyond the horizon', board: 'O..X.OX..', scale: 'norm', h: 1 },
  { name: 'e(s) not normalized', board: '.O.X.OXOX', scale: 'raw', h: 1 },
];
const OUT = { 1: 'win', 0: 'draw', '-1': 'loss' } as Record<string, string>;
const e = (b: Board) => LINES.filter(l => l.every(i => b[i] !== 'O')).length - LINES.filter(l => l.every(i => b[i] !== 'X')).length;
const BX = 20, BY = 34, C = 70, CX = 344, CW = 46;

/** Depth-limited minimax value of b with h plies left: utility ±1/0 if terminal, else e(s) (÷ 8 if normalized) at h = 0. */
function evaluator(scale: Scale) {
  const memo = new Map<string, number>();
  const ev = (b: Board, h: number): number => {
    const key = b + h;
    let v = memo.get(key);
    if (v !== undefined) return v;
    const w = winner(b), p = toMove(b);
    v = w ? (w === 'X' ? 1 : -1) : !b.includes('.') ? 0 : h === 0 ? e(b) / (scale === 'norm' ? 8 : 1)
      : empties(b).map(i => ev(put(b, i, p), h - 1)).reduce((x, y) => (p === 'X' ? Math.max(x, y) : Math.min(x, y)));
    memo.set(key, v);
    return v;
  };
  return ev;
}

/** Nodes generated by a depth-limited search of depth 1…n from b (move sequences, counted level by level over positions). */
function nodes(b: Board): number[] {
  const out: number[] = [];
  let cur = new Map([[b, 1]]), tot = 1;
  while (cur.size) {
    const next = new Map<Board, number>();
    for (const [x, k] of cur) if (!over(x)) for (const i of empties(x)) { const y = put(x, i, toMove(x)); next.set(y, (next.get(y) ?? 0) + k); }
    for (const k of next.values()) tot += k;
    if (next.size) out.push(tot);
    cur = next;
  }
  return out;
}

export function mount(el: HTMLElement, opts: FigOptions = {}) {
  style('fig-add-css', CSS);
  const c = card(el, 'interactive', 'Depth-limited minimax: the chosen move depends on the depth limit', '0 0 780 300');
  const evs = { raw: evaluator('raw'), norm: evaluator('norm') };
  let pre = PRESETS[0], scale: Scale = pre.scale, h = pre.h, count: number[] = [];

  // the board: each empty square shows the backed-up value of playing there
  const sq = Array.from({ length: 9 }, (_, i) => {
    const x = BX + (i % 3) * C, y = BY + Math.floor(i / 3) * C, g = s(c.svg, 'g', { class: 'add-sq' });
    s(g, 'rect', { x, y, width: C, height: C, class: 'add-cell' });
    const pick = s(g, 'rect', { x: x + 4, y: y + 4, width: C - 8, height: C - 8, rx: 8, class: 'add-pick' });
    s(g, 'text', { x: x + 5, y: y + 13, class: 'add-nm' }, cell(i));
    return { g, pick, mark: s(g, 'text', { x: x + C / 2, y: y + C / 2 + 2, class: 'add-mark' }), val: s(g, 'text', { x: x + C / 2, y: y + C / 2 + 2, class: 'add-val' }),
      out: s(g, 'text', { x: x + C - 5, y: y + C - 6, class: 'add-out', 'text-anchor': 'end' }) };
  });
  const under = s(c.svg, 'text', { x: BX, y: BY + 3 * C + 22, class: 'fg-m' });
  s(c.svg, 'text', { x: BX, y: 20, class: 'fg-t' }, 'backed-up value of each move');

  // right: the chosen move for every depth limit, its true outcome and the search cost
  s(c.svg, 'text', { x: CX - 6, y: 20, class: 'fg-t' }, 'For every depth limit h');
  [['h', 46], ['chosen move', 76], ['perfect play', 100], ['nodes searched', 128]].forEach(([t, y]) =>
    s(c.svg, 'text', { x: CX - 12, y: +y, class: 'fg-m', 'text-anchor': 'end' }, String(t)));
  const cols = Array.from({ length: 9 }, (_, k) => {
    const x = CX + k * CW, g = s(c.svg, 'g', { class: 'add-col' });
    g.onclick = () => set(k + 1);
    s(g, 'rect', { x, y: 30, width: CW - 6, height: 236, rx: 6, class: 'add-colbg' });
    s(g, 'text', { x: x + (CW - 6) / 2, y: 46, class: 'fg-t', 'text-anchor': 'middle' }, String(k + 1));
    return { g, mv: s(g, 'text', { x: x + (CW - 6) / 2, y: 77, class: 'add-mv', 'text-anchor': 'middle' }),
      out: s(g, 'text', { x: x + (CW - 6) / 2, y: 100, class: 'add-o', 'text-anchor': 'middle' }),
      bar: s(g, 'rect', { x: x + 10, width: CW - 26, rx: 2, class: 'add-bar' }),
      n: s(g, 'text', { x: x + (CW - 6) / 2, class: 'add-n', 'text-anchor': 'middle' }) };
  });

  const ctl = bar(c), pres = bar(c);
  const hIn = slider(ctl, 'depth limit h', 1, 9, 1, h, v => { h = v; render(); });
  hIn.addEventListener('change', say);
  const sc = document.createElement('select');
  sc.innerHTML = '<option value="raw">e(s) raw (−8 … 8), win = +1</option><option value="norm">e(s) ÷ 8, into [−1, 1], win = +1</option>';
  sc.onchange = () => { scale = sc.value as Scale; render(); say(); };
  ctl.append(sc);
  for (const p of PRESETS) {
    const btn = document.createElement('button');
    btn.className = 'btn sm';
    btn.textContent = p.name;
    btn.onclick = () => { load(p); say(); };
    pres.append(btn);
  }
  function set(v: number) { hIn.value = String(v); hIn.dispatchEvent(new Event('input')); say(); }
  function say() { opts.onEvent?.(`[${c.title}] ${pre.name}, h = ${h}, ${scale}: ${c.cap.textContent}`); }
  function load(p: typeof pre) {
    pre = p;
    scale = p.scale;
    sc.value = scale;
    count = nodes(p.board);
    hIn.max = String(count.length);
    hIn.value = String(p.h);
    hIn.dispatchEvent(new Event('input'));
  }

  const show = (v: number) => (scale === 'raw' ? String(v) : num(v, 3)).replace('-', '−');
  function choose(b: Board, depth: number) {
    const p = toMove(b), ev = evs[scale];
    let best = -1, bv = p === 'X' ? -Infinity : Infinity;
    for (const i of empties(b)) { const v = ev(put(b, i, p), depth - 1); if (p === 'X' ? v > bv : v < bv) { bv = v; best = i; } } // first strict improvement
    return { best, bv };
  }

  function render() {
    const b = pre.board, p = toMove(b), n = count.length, ev = evs[scale], target = minimax(b);
    const outcome = (i: number) => minimax(put(b, i, p)) * (p === 'X' ? 1 : -1); // for the player to move
    const { best } = choose(b, h);
    sq.forEach((q, i) => {
      const free = b[i] === '.', v = free ? ev(put(b, i, p), h - 1) : 0;
      q.mark.textContent = free ? '' : b[i];
      q.mark.setAttribute('class', `add-mark ${b[i] === 'X' ? 'x' : 'o'}`);
      q.val.textContent = free ? show(v) : '';
      q.val.setAttribute('class', `add-val${v > 0 ? ' pos' : v < 0 ? ' neg' : ''}`);
      q.out.textContent = free ? OUT[outcome(i)] : '';
      q.out.setAttribute('class', `add-out add-r${outcome(i) + 1}`);
      q.pick.classList.toggle('hide', i !== best);
    });
    under.textContent = `${p} to move · h = ${h} · tag: outcome with perfect play`;
    const lmax = Math.log10(count[n - 1]);
    cols.forEach((col, k) => {
      col.g.classList.toggle('hide', k >= n);
      if (k >= n) return;
      const m = choose(b, k + 1).best, o = outcome(m), bh = (Math.log10(count[k]) / lmax) * 110;
      col.mv.textContent = cell(m);
      col.out.textContent = OUT[o];
      col.out.setAttribute('class', `add-o add-r${o + 1}`);
      col.g.classList.toggle('now', k + 1 === h);
      col.g.classList.toggle('bad', o < target * (p === 'X' ? 1 : -1));
      col.bar.setAttribute('y', String(254 - bh));
      col.bar.setAttribute('height', String(bh));
      col.n.setAttribute('y', String(248 - bh));
      col.n.textContent = count[k] >= 1e4 ? `${num(count[k] / 1000, 3)}k` : String(count[k]);
    });
    explain(best, outcome);
  }

  function explain(best: number, outcome: (i: number) => number) {
    const b = pre.board, p = toMove(b), ev = evs[scale], moves = empties(b), n = count.length, top = Math.max(...moves.map(outcome));
    const v = ev(put(b, best, p), h - 1), o = outcome(best);
    const head = `With **h = ${h}** ${p} plays **${cell(best)}** (value ${show(v)}): with perfect play that move is a **${OUT[o]}**` +
      (o < top ? `, but ${moves.filter(i => outcome(i) === top).map(cell).join(', ')} would ${OUT[top] === 'win' ? 'win' : 'draw'}. ` : o === top ? ', the best possible. ' : '. ');
    const fix = Array.from({ length: n }, (_, k) => k + 1).find(d => d > h && outcome(choose(b, d).best) === top);
    const instant = moves.find(i => winner(put(b, i, p)) === p);
    let why = '';
    if (pre === PRESETS[0]) {
      const at2 = (i: number) => evs.raw(put(b, i, p), 1);
      why = h === 2 && scale === 'raw' ? `The slides' tree (p. 386): center ${at2(4)}, corner ${show(at2(0))}, edge ${show(at2(1))}. ` : '';
      const runs: string[] = [];
      for (let d = 1, from = 1; d <= n; d++) {
        const m = choose(b, d).best;
        if (d === n || choose(b, d + 1).best !== m) { runs.push(`${cell(m)} for h = ${from === d ? d : `${from}–${d}`}`); from = d + 1; }
      }
      why += `Chosen move by depth: ${runs.join(', ')}. ` + (h === n && moves.every(i => ev(put(b, i, p), n - 1) === v)
        ? `At full depth **every** first move is worth ${show(v)} (tic-tac-toe is a draw) and the first one wins the tie: $e(s)$ was only a **guess** that the center is better. ` : '');
    } else if (instant !== undefined && best !== instant && scale === 'raw')
      why = `**${cell(instant)} wins on the spot** (utility +1), yet the search prefers an **estimate** of ${show(v)}: with $e(s)$ up to 8 and wins worth 1 the scales do not match. ` +
        'Switch to $e(s) \\div 8$: estimates stay inside $(-1, 1)$ and a real win always beats them (slides p. 385). ';
    else if (o < top && fix)
      why = `**Horizon effect:** the search cannot see past ply ${h}; ${o < 0 ? 'the loss' : 'the win it misses'} only shows up with **h = ${fix}**, where the choice switches to ${cell(choose(b, fix).best)}. `;
    else if (o === top && h > 1 && outcome(choose(b, h - 1).best) < top)
      why = `One ply less (h = ${h - 1}) chose ${cell(choose(b, h - 1).best)}, a ${OUT[outcome(choose(b, h - 1).best)]}: the deeper search sees what the shallower one could not. `;
    c.cap.innerHTML = md(head + why + `Cost: **${count[h - 1].toLocaleString('en-US')} nodes** for h = ${h} (${count[n - 1].toLocaleString('en-US')} for the whole game from here).`);
  }

  load(pre);
  return { destroy() {} };
}

